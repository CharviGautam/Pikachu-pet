#!/usr/bin/env python3
"""
tools/gen_from_spec.py
Reads animations.spec.json, character.bible.json, and palette.json (or fallbacks).
Generates:
  1. src/generated/animations.ts
  2. src-tauri/src/generated_consts.rs
  3. src/shared/palette.css
  4. src/generated/palette.ts
  5. assets/prompts/generated/<anim>_<NN>.prompt.txt
  6. tools/expected_files.json
  7. public/assets/animations.json (initial manifest)
"""

import os
import json
import hashlib
from pathlib import Path

WORKSPACE = Path(__file__).resolve().parent.parent

SPEC_PATH = WORKSPACE / "assets" / "spec" / "animations.spec.json"
BIBLE_PATH = WORKSPACE / "assets" / "spec" / "character.bible.json"
PALETTE_PATH = WORKSPACE / "assets" / "spec" / "palette.json"

PROMPTS_DIR = WORKSPACE / "assets" / "prompts" / "generated"
SRC_GEN_DIR = WORKSPACE / "src" / "generated"
SRC_SHARED_DIR = WORKSPACE / "src" / "shared"
SRC_TAURI_DIR = WORKSPACE / "src-tauri" / "src"
PUBLIC_ASSETS_DIR = WORKSPACE / "public" / "assets"
TOOLS_DIR = WORKSPACE / "tools"

FALLBACK_PALETTE = {
    "--pup-fur-base": "#F2C77E",
    "--pup-fur-light": "#FBE8C4",
    "--pup-fur-shadow": "#D9A05B",
    "--pup-ear": "#C98A4B",
    "--pup-outline": "#7A4A2B",
    "--pup-nose": "#5B3A29",
    "--pup-eye": "#3E5C76",
    "--pup-blush": "#F4A8A0",
    "--fx-heart": "#FF7A93",
    "--fx-heart-light": "#FFC2CF",
    "--fx-zzz": "#8FA8E8",
    "--fx-spark": "#FFE9A8",
    "--bubble-bg": "#FFFDF7",
    "--bubble-text": "#5A3B27",
    "--shadow": "rgba(90,59,39,0.18)"
}

UI_LIGHT_VARS = {
    "--ui-bg": "#FBF7F0",
    "--ui-surface": "#FFFFFF",
    "--ui-text": "#3C2A1E",
    "--ui-muted": "#7C6A5C",
    "--ui-accent": "#E9A23B",
    "--ui-accent-contrast": "#2B1B0E",
    "--ui-border": "#E6DACB",
    "--ui-danger": "#C0473B",
    "--ui-focus": "#2F6FE4",
    "--radius-control": "8px",
    "--radius-card": "12px"
}

UI_DARK_VARS = {
    "--ui-bg": "#1F1712",
    "--ui-surface": "#2A2019",
    "--ui-text": "#F4E9DC",
    "--ui-muted": "#B5A594",
    "--ui-accent": "#F0B357",
    "--ui-accent-contrast": "#24160A",
    "--ui-border": "#41332A",
    "--ui-danger": "#E07A6E",
    "--ui-focus": "#7FA8FF"
}

CAMERA_TEXT = {
    "front": "Straight-on front view at eye level.",
    "three_quarter_right": "Three-quarter view, the character turned toward the viewer's right.",
    "side_right": "Pure side view, the character facing the viewer's right."
}

def compute_sha256(filepath: Path) -> str:
    h = hashlib.sha256()
    with open(filepath, "rb") as f:
        while chunk := f.read(65536):
            h.update(chunk)
    return h.hexdigest()

def load_json(filepath: Path):
    with open(filepath, "r", encoding="utf-8") as f:
        return json.load(f)

def ensure_dirs():
    for d in [PROMPTS_DIR, SRC_GEN_DIR, SRC_SHARED_DIR, SRC_TAURI_DIR, PUBLIC_ASSETS_DIR, TOOLS_DIR]:
        d.mkdir(parents=True, exist_ok=True)

def main():
    ensure_dirs()
    print("Reading specifications...")
    spec = load_json(SPEC_PATH)
    bible = load_json(BIBLE_PATH)

    spec_sha256 = compute_sha256(SPEC_PATH)

    if PALETTE_PATH.exists():
        print(f"Loading palette from {PALETTE_PATH}")
        pal_data = load_json(PALETTE_PATH)
        palette_tokens = {**FALLBACK_PALETTE, **pal_data.get("tokens", {})}
    else:
        print("Using fallback palette tokens")
        palette_tokens = FALLBACK_PALETTE.copy()

    canvas_px = spec.get("canvas_px", 384)
    baseline_y_px = spec.get("baseline_y_px", 356)
    center_x_px = spec.get("center_x_px", 192)
    display_logical_px = spec.get("display_size_logical_px", 192)
    window_logical_px = spec.get("window_size_logical_px", 256)
    feet_y_logical = 242

    animations = spec.get("animations", [])
    anim_names = [a["name"] for a in animations]

    # 1. Generate src/generated/animations.ts
    print("Generating src/generated/animations.ts...")
    ts_lines = [
        "// AUTO-GENERATED by tools/gen_from_spec.py - DO NOT HAND EDIT",
        f'export const SPEC_SHA256 = "{spec_sha256}";',
        f"export const CANVAS_PX = {canvas_px};",
        f"export const BASELINE_Y_PX = {baseline_y_px};",
        f"export const CENTER_X_PX = {center_x_px};",
        f"export const DISPLAY_LOGICAL_PX = {display_logical_px};",
        f"export const WINDOW_LOGICAL_PX = {window_logical_px};",
        f"export const FEET_Y_LOGICAL = {feet_y_logical};",
        "",
        "export const ANIMATION_NAMES = [",
    ]
    for name in anim_names:
        ts_lines.append(f'  "{name}",')
    ts_lines.extend([
        "] as const;",
        "",
        "export type AnimationName = (typeof ANIMATION_NAMES)[number];",
        "",
        'export type Camera = "front" | "three_quarter_right" | "side_right";',
        "",
        "export interface AnimationMeta {",
        "  name: AnimationName;",
        "  category: string;",
        '  priority: "mvp" | "v2";',
        "  camera: Camera;",
        "  mirrorable: boolean;",
        "  frames: number;",
        "  fps: number;",
        "  loop: boolean;",
        "  frameMs: number[];",
        "  soundCue?: { frame: number; sound: string };",
        "}",
        "",
        "export const ANIMATIONS: Record<AnimationName, AnimationMeta> = {",
    ])

    for a in animations:
        name = a["name"]
        frames = a.get("frames", 1)
        fps = a.get("fps", 6)
        frame_ms_map = a.get("frame_ms", {})
        default_ms = int(round(1000.0 / fps)) if fps > 0 else 167

        resolved_frame_ms = []
        for i in range(frames):
            ms_val = frame_ms_map.get(str(i), default_ms)
            resolved_frame_ms.append(int(ms_val))

        meta = {
            "name": name,
            "category": a.get("category", "core"),
            "priority": a.get("priority", "mvp"),
            "camera": a.get("camera", "front"),
            "mirrorable": bool(a.get("mirrorable", True)),
            "frames": frames,
            "fps": fps,
            "loop": bool(a.get("loop", False)),
            "frameMs": resolved_frame_ms,
        }
        if "soundCue" in a:
            meta["soundCue"] = a["soundCue"]

        ts_lines.append(f'  "{name}": {json.dumps(meta, indent=2).replace(chr(10), chr(10) + "  ")},')

    ts_lines.append("};")
    ts_lines.append("")

    with open(SRC_GEN_DIR / "animations.ts", "w", encoding="utf-8") as f:
        f.write("\n".join(ts_lines))

    # 2. Generate src-tauri/src/generated_consts.rs
    print("Generating src-tauri/src/generated_consts.rs...")
    rs_lines = [
        "// AUTO-GENERATED by tools/gen_from_spec.py - DO NOT HAND EDIT",
        f'pub const SPEC_SHA256: &str = "{spec_sha256}";',
        f"pub const CANVAS_PX: u32 = {canvas_px};",
        f"pub const BASELINE_Y_PX: u32 = {baseline_y_px};",
        f"pub const CENTER_X_PX: u32 = {center_x_px};",
        f"pub const DISPLAY_LOGICAL_PX: u32 = {display_logical_px};",
        f"pub const WINDOW_LOGICAL_PX: u32 = {window_logical_px};",
        f"pub const FEET_Y_LOGICAL: u32 = {feet_y_logical};",
        "",
    ]
    with open(SRC_TAURI_DIR / "generated_consts.rs", "w", encoding="utf-8") as f:
        f.write("\n".join(rs_lines))

    # 3. Generate src/shared/palette.css
    print("Generating src/shared/palette.css...")
    css_lines = [
        "/* AUTO-GENERATED by tools/gen_from_spec.py - DO NOT HAND EDIT */",
        ":root {",
    ]
    for k, v in palette_tokens.items():
        css_lines.append(f"  {k}: {v};")
    for k, v in UI_LIGHT_VARS.items():
        css_lines.append(f"  {k}: {v};")
    css_lines.extend([
        "}",
        "",
        "@media (prefers-color-scheme: dark) {",
        "  :root {",
    ])
    for k, v in UI_DARK_VARS.items():
        css_lines.append(f"    {k}: {v};")
    css_lines.extend([
        "  }",
        "}",
        "",
    ])
    with open(SRC_SHARED_DIR / "palette.css", "w", encoding="utf-8") as f:
        f.write("\n".join(css_lines))

    # 4. Generate src/generated/palette.ts
    print("Generating src/generated/palette.ts...")
    pal_ts_lines = [
        "// AUTO-GENERATED by tools/gen_from_spec.py - DO NOT HAND EDIT",
        "export const PALETTE = {",
    ]
    for k, v in palette_tokens.items():
        clean_key = k.lstrip("-").replace("-", "_")
        pal_ts_lines.append(f'  "{clean_key}": "{v}",')
        pal_ts_lines.append(f'  "{k}": "{v}",')
    pal_ts_lines.extend([
        "} as const;",
        "",
        "export type PaletteToken = keyof typeof PALETTE;",
        "",
    ])
    with open(SRC_GEN_DIR / "palette.ts", "w", encoding="utf-8") as f:
        f.write("\n".join(pal_ts_lines))

    # 5. Generate prompts in assets/prompts/generated/
    print("Generating prompt files...")
    style_lock = bible.get("style_lock", "").strip()
    neg_list = "; ".join(bible.get("negative_list", []))
    camera_refs = bible.get("camera_refs", {})

    total_prompts = 0
    for a in animations:
        anim_name = a["name"]
        camera = a.get("camera", "front")
        frames = a.get("frames", 1)
        descriptions = a.get("frame_descriptions", [])
        cam_desc = CAMERA_TEXT.get(camera, "")

        base_refs = camera_refs.get(camera, ["approved/master/master_front.png"])
        ref1 = f"assets/{base_refs[0]}" if len(base_refs) > 0 else "assets/approved/master/master_front.png"
        ref2 = f"assets/{base_refs[1]}" if len(base_refs) > 1 else ref1

        for k in range(frames):
            desc = descriptions[k] if k < len(descriptions) else f"Frame {k} of {anim_name}"
            out_file = f"assets/raw/{anim_name}/{anim_name}_{k:02d}.png"

            if k == 0:
                refs_header = f"{ref1} | {ref2}"
                continuity_line = ""
            else:
                prev_frame_ref = f"assets/raw/{anim_name}/{anim_name}_{k-1:02d}.png"
                refs_header = f"{ref1} | {ref2} | {prev_frame_ref}"
                continuity_line = "image 3 = the previous approved frame of this same animation: keep the identical scale, framing, horizontal centring and feet height."

            prompt_content = f"""# output: {out_file}
# refs: {refs_header}
# aspect: 1:1
# size: 1K
# animation: {anim_name}  frame: {k+1}  of: {frames}  attempt: 1
---
{style_lock}

REFERENCES: image 1 = the character's identity truth for this camera; image 2 = a second identity check;
{continuity_line}

SHOT: animation "{anim_name}", frame {k+1} of {frames}. {cam_desc}
POSE: {desc}
CONTINUITY: Same size, same screen position and same outline thickness as the references. Change ONLY what POSE describes. Do not add props, text, shadows or effects.
AVOID: {neg_list}
"""
            prompt_file = PROMPTS_DIR / f"{anim_name}_{k:02d}.prompt.txt"
            with open(prompt_file, "w", encoding="utf-8") as f:
                f.write(prompt_content.strip() + "\n")
            total_prompts += 1

    print(f"Generated {total_prompts} prompt files.")

    # 6. Generate tools/expected_files.json
    print("Generating tools/expected_files.json...")
    expected = {
        "specSha256": spec_sha256,
        "tiers": {
            "mvp": {
                "animations": [],
                "raw_frames": [],
                "processed_frames": [],
                "strips": []
            },
            "v2": {
                "animations": [],
                "raw_frames": [],
                "processed_frames": [],
                "strips": []
            },
            "placeholder": {
                "strips": []
            }
        }
    }

    for a in animations:
        tier = a.get("priority", "mvp")
        name = a["name"]
        frames = a.get("frames", 1)

        expected["tiers"][tier]["animations"].append(name)
        strip_path = f"public/assets/sprites/{name}.png"
        expected["tiers"][tier]["strips"].append(strip_path)
        expected["tiers"]["placeholder"]["strips"].append(strip_path)

        for k in range(frames):
            raw_path = f"assets/raw/{name}/{name}_{k:02d}.png"
            proc_path = f"assets/processed/{name}/{name}_{k:02d}.png"
            expected["tiers"][tier]["raw_frames"].append(raw_path)
            expected["tiers"][tier]["processed_frames"].append(proc_path)

    with open(TOOLS_DIR / "expected_files.json", "w", encoding="utf-8") as f:
        json.dump(expected, f, indent=2)

    # 7. Generate public/assets/animations.json (initial manifest)
    print("Generating public/assets/animations.json...")
    manifest = {
        "version": 1,
        "canvas": canvas_px,
        "baseline": baseline_y_px,
        "centerX": center_x_px,
        "display": display_logical_px,
        "window": window_logical_px,
        "feetYLogical": feet_y_logical,
        "specSha256": spec_sha256,
        "animations": {}
    }

    for a in animations:
        name = a["name"]
        frames = a.get("frames", 1)
        fps = a.get("fps", 6)
        frame_ms_map = a.get("frame_ms", {})
        default_ms = int(round(1000.0 / fps)) if fps > 0 else 167

        resolved_frame_ms = []
        bboxes = []
        for i in range(frames):
            ms_val = frame_ms_map.get(str(i), default_ms)
            resolved_frame_ms.append(int(ms_val))
            # Default placeholder bbox: [x, y, w, h] roughly centered
            bboxes.append([48, 56, 288, 300])

        manifest["animations"][name] = {
            "strip": f"sprites/{name}.png",
            "frames": frames,
            "frameWidth": canvas_px,
            "frameHeight": canvas_px,
            "fps": fps,
            "loop": bool(a.get("loop", False)),
            "frameMs": resolved_frame_ms,
            "camera": a.get("camera", "front"),
            "mirrorable": bool(a.get("mirrorable", True)),
            "bbox": bboxes,
            "soundCue": a.get("soundCue", None)
        }

    with open(PUBLIC_ASSETS_DIR / "animations.json", "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)

    print("gen_from_spec.py completed successfully!")

if __name__ == "__main__":
    main()
